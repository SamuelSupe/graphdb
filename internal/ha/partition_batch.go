package ha

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"

	"github.com/SamuelSupe/graphdb/v2/internal/partition"
	"github.com/SamuelSupe/graphdb/v2/internal/storage"
	"golang.org/x/sync/errgroup"
)

func (c *Cluster) registerFragmentBatch(mux *http.ServeMux) {
	mux.HandleFunc("POST /cluster/graph/fragment-batch", func(w http.ResponseWriter, r *http.Request) {
		if c.config.Protocol < partition.BatchProtocol {
			http.Error(w, "fragment batches require Raft protocol 8", http.StatusNotImplemented)
			return
		}
		if c.App.Catalog || c.App.ShardID == "" {
			http.Error(w, "fragment batches require a data group", http.StatusConflict)
			return
		}
		var actions []partition.Action
		decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, partition.MaxFragmentBatchBytes))
		decoder.DisallowUnknownFields()
		if decoder.Decode(&actions) != nil {
			http.Error(w, "invalid fragment batch", http.StatusBadRequest)
			return
		}
		if err := partition.ValidateFragmentBatch(actions); err != nil {
			c.partitionError(w, err)
			return
		}
		if storage.ValidateTenantID(actions[0].Tenant) != nil || actions[0].Generation <= 0 {
			c.partitionError(w, fmt.Errorf("%w: invalid fragment batch scope", storage.ErrInvalidArgument))
			return
		}
		for _, action := range actions {
			if action.GCSweep != nil {
				c.partitionError(w, fmt.Errorf("%w: GC candidates are generated by the data group", storage.ErrInvalidArgument))
				return
			}
		}
		if actions[0].Operation == "prepare" || actions[0].Operation == "data_gc_begin" {
			if err := c.App.Store.CheckWriteDiskSpace(r.Context(), partition.MaxChangeBytes*2); err != nil {
				c.partitionError(w, err)
				return
			}
		}
		for i := range actions {
			actions[i].Revision = partition.BatchGCRevision
			if actions[i].Operation == "data_gc_begin" && c.config.Protocol >= partition.BufferedGCProtocol {
				actions[i].Revision = partition.BufferedGCRevision
			}
			if actions[i].Operation == "prepare" && c.config.Protocol >= partition.BalancedLeafProtocol {
				actions[i].Revision = partition.BalancedLeafRevision
			}
		}
		if c.config.Protocol >= partition.PlannedGCProtocol && actions[0].Operation == "data_gc_step" && actions[0].Purpose != "cancel" {
			if err := c.planGCSteps(r.Context(), actions); err != nil {
				c.partitionError(w, err)
				return
			}
		}
		cmd, err := newCommand("graph_fragment_batch")
		if err == nil {
			cmd.Tenant = actions[0].Tenant
			cmd.Body, err = json.Marshal(actions)
		}
		if err != nil {
			c.partitionError(w, err)
			return
		}
		data, err := c.propose(r.Context(), cmd)
		if err != nil {
			c.writeError(w, err)
			return
		}
		writeResult(w, data)
	})
}

// Distinct partitions have independent keys. All workers join before the
// application can commit or roll back its shared journal.
func (a *Application) applyFragmentBatch(ctx context.Context, cmd command) (_ []byte, err error) {
	var actions []partition.Action
	if err := json.Unmarshal(cmd.Body, &actions); err != nil {
		return nil, err
	}
	if err := partition.ValidateFragmentBatch(actions); err != nil {
		return resultJSON(http.StatusBadRequest, map[string]string{"error": err.Error()})
	}
	if a.Catalog || a.ShardID == "" || actions[0].Tenant != cmd.Tenant {
		return resultJSON(http.StatusConflict, map[string]string{"error": "fragment batch requires a matching data-group tenant"})
	}
	if storage.ValidateTenantID(cmd.Tenant) != nil || actions[0].Generation <= 0 {
		return resultJSON(http.StatusBadRequest, map[string]string{"error": "invalid fragment batch scope"})
	}
	operation := actions[0].Operation
	metric := "partition_fragment_" + operation
	if operation == "data_gc_step" {
		metric = "partition_gc_apply"
	}
	finish := a.metrics.Start(metric)
	defer func() { finish(err) }()
	store := a.partitionStore()
	writes := make([]map[string][]byte, len(actions))
	reclaims := make([][]string, len(actions))
	results := make([]any, len(actions))
	failures := make([]error, len(actions))
	var workers errgroup.Group
	workers.SetLimit(8)
	for i, action := range actions {
		workers.Go(func() error {
			buffer := &bufferedFragment{FileStore: a.Files, writes: make(map[string][]byte)}
			value, err := a.partitionStoreFor(buffer).ApplyFragment(ctx, action)
			if errors.Is(err, errBufferedFragmentTooLarge) {
				value, err = store.ApplyFragment(ctx, action)
			} else if err == nil {
				writes[i] = buffer.writes
				reclaims[i] = buffer.reclaim
			}
			failures[i] = err
			if err == nil {
				switch action.Operation {
				case "prepare":
					results[i] = value
				case "data_gc_begin", "data_gc_step":
					if value.(partition.DataState).GC != nil {
						results[i] = partition.DataState{GC: &partition.DataGC{}}
					}
				}
			}
			return nil
		})
	}
	_ = workers.Wait()
	var rejected error
	for _, err := range failures {
		if err == nil {
			continue
		}
		_, code := partitionErrorStatus(err)
		if code == "shard_unavailable" || code == "partition_corrupt" {
			return nil, err
		}
		if rejected == nil {
			rejected = err
		}
	}
	if rejected != nil {
		status, code := partitionErrorStatus(rejected)
		response, err := resultJSON(status, map[string]string{"code": code, "error": rejected.Error()})
		if err != nil {
			return nil, fmt.Errorf("encode fragment rejection: %w", err)
		}
		return nil, &storage.ReplicationRejectedError{Response: response}
	}
	if err := a.flushBufferedFragments(ctx, writes, operation); err != nil {
		return nil, err
	}
	for _, keys := range reclaims {
		if len(keys) != 0 {
			if err := a.Files.DeferReplicatedPageReclaim(ctx, keys); err != nil {
				return nil, err
			}
		}
	}
	return resultJSON(http.StatusOK, results)
}
