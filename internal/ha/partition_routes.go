func (a *Application) partitionStore() partition.Store {
	return a.partitionStoreFor(a.Files)
}

func (a *Application) partitionStoreFor(objects storage.ObjectStore) partition.Store {
	return partition.Store{Objects: objects, Prefix: a.Store.Prefix, ReadIngestInput: func(ctx context.Context, tenant string, generation int64, ref string) ([]byte, error) {
		return a.readPartitionIngestInput(ctx, objects, tenant, generation, ref)
	}}
}

type graphDescriptor struct {
	graph partition.Graph
	etag  string
	err   error
}

func (a *Application) graphDescriptor(ctx context.Context, tenant string) (partition.Graph, error) {
	entry := a.cachedGraphDescriptor(ctx, tenant)
	return entry.graph, entry.err
}

func (a *Application) cachedGraphDescriptor(ctx context.Context, tenant string) graphDescriptor {
	a.mu.RLock()
	defer a.mu.RUnlock()
	a.graphCacheMu.Lock()
	defer a.graphCacheMu.Unlock()
	if entry, ok := a.graphCache[tenant]; ok {
		return entry
	}
	g, err := a.partitionStore().GetGraph(ctx, tenant)
	entry := graphDescriptor{graph: g, err: err}
	if err == nil {
		data, marshalErr := json.Marshal(g)
		if marshalErr != nil {
			return graphDescriptor{err: marshalErr}
		}
		entry.etag = fmt.Sprintf(`"%x"`, sha256.Sum256(data))
	} else if !errors.Is(err, storage.ErrNotFound) {
		return entry
	}
	if a.graphCache == nil || len(a.graphCache) >= 128 {
		a.graphCache = make(map[string]graphDescriptor)
	}
	a.graphCache[tenant] = entry
	return entry
}

func (c *Cluster) partitionAction(ctx context.Context, action partition.Action) ([]byte, error) {
	if c.config.Protocol < 5 || c.App.Catalog || c.App.ShardID == "" {
		return nil, fmt.Errorf("graph partitions require a protocol-5 data group")
	}
	if storage.ValidateTenantID(action.Tenant) != nil || action.Generation <= 0 {
		return nil, fmt.Errorf("%w: invalid graph scope", storage.ErrInvalidArgument)
	}
	if action.GCSweep != nil {
		return nil, fmt.Errorf("%w: GC candidates are generated by the data group", storage.ErrInvalidArgument)
	}
	if len(action.PreparedBatch) != 0 && (action.Operation != "commit" || c.config.Protocol < partition.BatchProtocol) {
		return nil, fmt.Errorf("%w: batched prepare receipts require protocol %d graph publication", storage.ErrConflict, partition.BatchProtocol)
	}
	if action.ReceiptRef != "" && (action.Operation != "complete" || c.config.Protocol < partition.BatchProtocol) {
		return nil, fmt.Errorf("%w: atomic graph receipt completion requires protocol %d", storage.ErrConflict, partition.BatchProtocol)
	}
	if c.config.Protocol < partition.IngestProtocol && (action.Purpose == "ingest" || action.IngestResult != nil) {
		return nil, fmt.Errorf("%w: partitioned ingest requires home Raft protocol %d", storage.ErrConflict, partition.IngestProtocol)
	}
	if c.config.Protocol < partition.CompactIngestProtocol {
		if action.Operation == "graph_gc_inputs" {
			return nil, fmt.Errorf("%w: graph input GC requires home Raft protocol %d", storage.ErrConflict, partition.CompactIngestProtocol)
		}
		for _, input := range action.Inputs {
			if input.Acceptance != "" {
				return nil, fmt.Errorf("%w: graph ingest acceptance references require home Raft protocol %d", storage.ErrConflict, partition.CompactIngestProtocol)
			}
		}
	}
	c.App.mu.RLock()
	var scopeErr error
	var state partition.DataState
	switch action.Operation {
	case "initialize", "reserve", "reserve_partitions", "data_move_reserve":
	case "prepare", "finalize", "discard", "fence", "data_move_page", "data_move_pages", "data_move_fence", "data_move_install", "data_move_thaw", "data_move_retire", "data_move_capture", "data_gc_begin", "data_gc_step":
		state, scopeErr = c.App.partitionStore().Data(ctx, action.Tenant, action.Generation, action.Partition)
	default:
		var g partition.Graph
		g, scopeErr = c.App.partitionStore().GetGraph(ctx, action.Tenant)
		if scopeErr == nil && g.Generation != action.Generation {
			scopeErr = fmt.Errorf("%w: graph generation changed", storage.ErrConflict)
		}
	}
	c.App.mu.RUnlock()
	if scopeErr != nil {
		return nil, scopeErr
	}
	if action.Operation == "prepare" || action.Operation == "stage_input" || action.Operation == "data_gc_begin" || action.Operation == "data_move_page" || action.Operation == "data_move_pages" {
		if err := c.App.Store.CheckWriteDiskSpace(ctx, int64(len(action.Data))+partition.MaxChangeBytes*2); err != nil {
			return nil, err
		}
	}
	if action.Operation == "data_move_install" {
		verified, err := c.App.partitionStore().VerifyMoveStep(ctx, action)
		if err != nil {
			return nil, err
		}
		action.Verify = verified
	}
	cmd, err := newCommand("graph_partition")
	if err != nil {
		return nil, err
	}
	if action.Operation == "pin" || strings.HasPrefix(action.Operation, "graph_move_") || strings.HasPrefix(action.Operation, "graph_gc_") {
		action.At = cmd.At
	}
	action.Revision = partition.ActionRevision
	if c.config.Protocol >= partition.CompactIngestProtocol && (action.Operation == "begin" || action.Operation == "graph_gc_begin") {
		action.Revision = partition.InputGCRevision
	}
	if c.config.Protocol >= partition.BatchProtocol && action.Operation == "begin" {
		action.Revision = partition.BatchGCRevision
	}
	if c.config.Protocol >= partition.BufferedGCProtocol && action.Operation == "data_gc_begin" {
		action.Revision = partition.BufferedGCRevision
	}
	if c.config.Protocol >= partition.BalancedLeafProtocol && action.Operation == "prepare" {
		action.Revision = partition.BalancedLeafRevision
	}
	if c.config.Protocol >= partition.PlannedGCProtocol && action.Operation == "data_gc_step" && action.Purpose != "cancel" && state.GC != nil && state.GC.Phase == "sweep" {
		if err := c.planGCStep(ctx, &action, state); err != nil {
			return nil, err
		}
	}
	cmd.Tenant = action.Tenant
	cmd.Body, err = json.Marshal(action)
	if err != nil {
		return nil, err
	}
	return c.propose(ctx, cmd)
}

func (c *Cluster) registerPartitionRoutes(mux *http.ServeMux) {
	c.registerPartitionEnable(mux)
	c.registerPartitionMove(mux)
	c.registerPartitionGC(mux)
	ready := func(w http.ResponseWriter, r *http.Request) bool {
		if c.config.Protocol < 5 || c.App.Catalog || c.App.ShardID == "" {
			http.Error(w, "graph partitions require protocol 5", http.StatusConflict)
			return false
		}
		if err := c.Node.ReadBarrier(r.Context()); err != nil {
			c.writeError(w, err)
			return false
		}
		return true
	}
	c.registerFragmentBatch(mux)
	mux.HandleFunc("GET /cluster/graph/descriptor/{tenant}", func(w http.ResponseWriter, r *http.Request) {
		if !ready(w, r) {
			return
		}
		tenant := r.PathValue("tenant")
		if storage.ValidateTenantID(tenant) != nil {
			http.Error(w, "invalid tenant", http.StatusBadRequest)
			return
		}
		entry := c.App.cachedGraphDescriptor(r.Context(), tenant)
		if entry.err != nil {
			c.partitionError(w, entry.err)
			return
		}
		w.Header().Set("ETag", entry.etag)
		if r.Header.Get("If-None-Match") == entry.etag {
			w.WriteHeader(http.StatusNotModified)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(entry.graph)
	})
	mux.HandleFunc("GET /cluster/graph/transactions/{tenant}/{identity}", func(w http.ResponseWriter, r *http.Request) {
		if !ready(w, r) {
			return
		}
		tenant := r.PathValue("tenant")
		generation, err := strconv.ParseInt(r.URL.Query().Get("generation"), 10, 64)
		if err != nil || generation <= 0 || storage.ValidateTenantID(tenant) != nil || len(r.PathValue("identity")) > 512 {
			http.Error(w, "invalid graph transaction scope", http.StatusBadRequest)
			return
		}
		c.App.mu.RLock()
		g, err := c.App.partitionStore().GetGraph(r.Context(), tenant)
		var txn partition.Transaction
		if err == nil && g.Generation != generation {
			err = fmt.Errorf("%w: graph generation changed", storage.ErrConflict)
		}
		if err == nil {
			txn, err = c.App.partitionStore().Transaction(r.Context(), tenant, generation, r.PathValue("identity"))
		}
		c.App.mu.RUnlock()
		if err != nil {
			c.partitionError(w, err)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(txn)
	})
	mux.HandleFunc("GET /cluster/graph/pins/{tenant}/{pin}", func(w http.ResponseWriter, r *http.Request) {
		if !ready(w, r) {
			return
		}
		c.App.mu.RLock()
		value, err := c.App.partitionStore().Pinned(r.Context(), r.PathValue("tenant"), r.PathValue("pin"), r.URL.Query().Get("query"), time.Now().UTC())
		c.App.mu.RUnlock()
		if err != nil {
			c.partitionError(w, err)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(value)
	})
	mux.HandleFunc("POST /cluster/graph/action", func(w http.ResponseWriter, r *http.Request) {
		var action partition.Action
		decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 16<<20))
		decoder.DisallowUnknownFields()
		if decoder.Decode(&action) != nil {
			http.Error(w, "invalid partition action", http.StatusBadRequest)
			return
		}
		fencedIngest := c.config.Protocol >= partition.BatchProtocol &&
			(action.Operation == "begin" && action.Purpose == "ingest" ||
				action.Operation == "commit" && len(action.PreparedBatch) != 0 ||
				action.Operation == "complete" && action.ReceiptRef != "")
		if !fencedIngest && !ready(w, r) {
			return
		}
		data, err := c.partitionAction(r.Context(), action)
		if err != nil {
			c.partitionError(w, err)
			return
		}
		writeResult(w, data)
	})
	mux.HandleFunc("POST /cluster/graph/input", func(w http.ResponseWriter, r *http.Request) {
		if !ready(w, r) {
			return
		}
		var input partition.Action
		decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4096))
		decoder.DisallowUnknownFields()
		if decoder.Decode(&input) != nil || storage.ValidateTenantID(input.Tenant) != nil || input.Generation <= 0 || len(input.Inputs) != 1 {
			http.Error(w, "invalid graph input reference", http.StatusBadRequest)
			return
		}
		c.App.mu.RLock()
		data, err := c.App.partitionStore().Input(r.Context(), input.Tenant, input.Generation, input.Inputs[0])
		c.App.mu.RUnlock()
		if err != nil {
			c.partitionError(w, err)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(map[string]any{"data": data})
	})
	fragmentRead := func(w http.ResponseWriter, r *http.Request) {
		if c.config.Protocol < 5 || c.App.Catalog || c.App.ShardID == "" {
			http.Error(w, "graph partitions require protocol 5", http.StatusConflict)
			return
		}
		var input partition.ReadRequest
		var batch []partition.ReadRequest
		decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4<<20))
		decoder.DisallowUnknownFields()
		isBatch := r.URL.Path == "/cluster/graph/read-batch"
		var target any = &input
		if isBatch {
			target = &batch
		}
		if decoder.Decode(target) != nil {
			http.Error(w, "invalid partition read", http.StatusBadRequest)
			return
		}
		read := func() (any, error) {
			c.App.mu.RLock()
			defer c.App.mu.RUnlock()
			if isBatch {
				return c.App.partitionStore().ReadBatch(r.Context(), batch)
			}
			return c.App.partitionStore().Read(r.Context(), input)
		}
		result, err := read()
		// The home group already selected an immutable root. A successful
		// local read needs no quorum round trip on the data group. On a miss
		// or epoch mismatch, wait for the leader to apply before classifying it.
		if errors.Is(err, storage.ErrNotFound) || errors.Is(err, storage.ErrConflict) || errors.Is(err, partition.ErrPartitionCorrupt) {
			if err := c.Node.ReadBarrier(r.Context()); err != nil {
				c.writeError(w, err)
				return
			}
			result, err = read()
		}
		if err != nil {
			c.partitionError(w, err)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(result)
	}
	mux.HandleFunc("POST /cluster/graph/read", fragmentRead)
	mux.HandleFunc("POST /cluster/graph/read-batch", fragmentRead)
}

func partitionErrorStatus(err error) (int, string) {
	switch {
	case errors.Is(err, partition.ErrInputExpired):
		return http.StatusConflict, "graph_input_expired"
	case errors.Is(err, partition.ErrVersionNotReady):
		return http.StatusServiceUnavailable, "reader_not_fresh"
	case errors.Is(err, partition.ErrGraphBusy):
		return http.StatusTooManyRequests, "graph_busy"
	case errors.Is(err, partition.ErrPartitionCorrupt):
		return http.StatusInternalServerError, "partition_corrupt"
	case errors.Is(err, storage.ErrNotFound):
		return http.StatusNotFound, "not_found"
	case errors.Is(err, partition.ErrPlacementChanged):
		return http.StatusConflict, "graph_layout_changed"
	case errors.Is(err, storage.ErrConflict):
		return http.StatusConflict, "graph_conflict"
	case errors.Is(err, storage.ErrInvalidArgument):
		return http.StatusBadRequest, "bad_request"
	default:
		return http.StatusServiceUnavailable, "shard_unavailable"
	}
}

func (c *Cluster) partitionError(w http.ResponseWriter, err error) {
	status, code := partitionErrorStatus(err)
	data, _ := resultJSON(status, map[string]any{"code": code, "error": err.Error(), "retryable": status == 503 || status == 429 || code == "graph_layout_changed" || code == "graph_input_expired"})
	writeResult(w, data)
}
